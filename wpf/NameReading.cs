            ['挣'] = new[] { E('挣', "zhēng", "挣扎", '争'), E('挣', "zhèng", "挣钱", '政') },
            ['症'] = new[] { E('症', "zhèng", "症状", '政'), E('症', "zhēng", "症结", '征') },
            ['俩'] = new[] { E('俩', "liǎng", "伎俩", '两') },
        };

        /// <summary>该学生实际交给语音引擎朗读的文本：优先“读音”，否则原名。</summary>
        public static string Spoken(Student? student)
        {
            if (student == null) return "";
            return string.IsNullOrWhiteSpace(student.reading) ? student.name : student.reading.Trim();
        }

        public static bool IsPolyphonic(char c) => Map.ContainsKey(c);

        public static IReadOnlyList<ReadingOption> OptionsFor(char c)
        {
            return Map.TryGetValue(c, out var options) ? options : Array.Empty<ReadingOption>();
        }

        /// <summary>按每个字位选择的读音拼出朗读文本；未选择的字保持原样。</summary>
        public static string Compose(string name, IReadOnlyDictionary<int, ReadingOption> picks)
        {
            if (string.IsNullOrEmpty(name) || picks == null || picks.Count == 0) return name ?? "";
            var chars = name.ToCharArray();
            foreach (var kv in picks)
                if (kv.Value != null && kv.Key >= 0 && kv.Key < chars.Length)
                    chars[kv.Key] = kv.Value.Homophone;
            return new string(chars);
        }

        public static bool SelfTest(out string detail)
        {
            var zeng = OptionsFor('曾').FirstOrDefault(o => o.Pinyin == "zēng");
            var yue = OptionsFor('乐').FirstOrDefault(o => o.Pinyin == "yuè");
            bool optionsOk = zeng != null && zeng.Homophone == '增'
                          && yue != null && yue.Homophone == '月';
            string composed = Compose("曾小乐", new Dictionary<int, ReadingOption>
            {
                [0] = zeng ?? throw new InvalidOperationException("缺少「曾」读音"),
                [2] = yue ?? throw new InvalidOperationException("缺少「乐」读音")
            });
            bool spokenOk = Spoken(new Student { name = "曾小乐" }) == "曾小乐"
                         && Spoken(new Student { name = "曾小乐", reading = "增小月" }) == "增小月"
                         && Spoken(new Student { name = "曾小乐", reading = "  " }) == "曾小乐";
            detail = "曾→增 / 乐→月，朗读=" + composed + "，候选数=" + Map.Count;
            return optionsOk && spokenOk && composed == "增小月";
        }
    }
